"""metrics-sync: copy the governed metric definitions out of dbt.

Reads dbt's target/semantic_manifest.json (the parsed MetricFlow YAML) and writes:
  1. docs/metric_catalog.md       the metric catalogue for people (exam Q6)
  2. semantic.metric_catalog      the same catalogue for the AI assistant (role publisher)
  3. (wave 4) Superset datasets    metric expressions copied into certified datasets

Nothing is translated or rewritten: each consumer receives the sql_expression declared
once in dbt/models/semantic/_metrics.yml, so every surface computes the same thing.

Usage:
    python metrics_sync.py markdown --manifest dbt/target/semantic_manifest.json \
        --out docs/metric_catalog.md
    python metrics_sync.py database --manifest dbt/target/semantic_manifest.json
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import asdict, dataclass, field
from pathlib import Path

GOVERNED_ORDER = [
    "trips",
    "total_revenue",
    "avg_fare",
    "avg_tip",
    "tip_rate",
    "avg_distance",
    "avg_duration",
    "revenue_per_mile",
    "trips_per_active_hour",
    "airport_trips",
    "congestion_fee_revenue",
    "valid_trip_rate",
    "airport_fee_revenue",
    "congestion_surcharge_revenue",
    "est_co2_kg",
]
EXAM_METRICS = set(GOVERNED_ORDER[:12])


@dataclass
class MetricDefinition:
    name: str
    label: str
    description: str
    metric_type: str
    role: str  # governed | base
    required_by_exam: bool
    owner: str
    unit: str
    grains: list[str]
    base_table: str
    sql_expression: str
    filters: str
    is_estimate: bool
    metricflow_filter: str | None
    inputs: list[str] = field(default_factory=list)
    source: str | None = None


def _filter_text(value) -> str | None:
    if not value:
        return None
    items = value.get("where_filters", []) if isinstance(value, dict) else value
    texts = [i.get("where_sql_template", "") if isinstance(i, dict) else str(i) for i in items]
    return " and ".join(t for t in texts if t) or None


def _inputs(type_params: dict) -> list[str]:
    names = []
    for key in ("measure", "numerator", "denominator"):
        value = type_params.get(key)
        if isinstance(value, dict) and value.get("name"):
            names.append(f"{key}: {value['name']}")
    for metric in type_params.get("metrics") or []:
        names.append(f"metric: {metric.get('name')}")
    if type_params.get("expr") and type_params.get("metrics"):
        names.append(f"expr: {type_params['expr']}")
    return names


def load_catalog(manifest_path: Path) -> list[MetricDefinition]:
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    rows = []
    for metric in manifest.get("metrics", []):
        meta = (metric.get("config") or {}).get("meta") or {}
        if not meta.get("sql_expression"):
            raise ValueError(f"metric {metric['name']} has no meta.sql_expression")
        rows.append(
            MetricDefinition(
                name=metric["name"],
                label=metric.get("label") or metric["name"],
                description=" ".join((metric.get("description") or "").split()),
                metric_type=metric.get("type", ""),
                role=meta.get("role", "governed"),
                required_by_exam=metric["name"] in EXAM_METRICS,
                owner=meta.get("owner", ""),
                unit=meta.get("unit", ""),
                grains=list(meta.get("grains", [])),
                base_table=meta.get("base_table", ""),
                sql_expression=" ".join(str(meta["sql_expression"]).split()),
                filters=meta.get("filters", ""),
                is_estimate=bool(meta.get("is_estimate", False)),
                metricflow_filter=_filter_text(metric.get("filter")),
                inputs=_inputs(metric.get("type_params") or {}),
                source=meta.get("source"),
            )
        )
    order = {name: i for i, name in enumerate(GOVERNED_ORDER)}
    rows.sort(key=lambda r: (r.role != "governed", order.get(r.name, 99), r.name))
    return rows


def to_markdown(rows: list[MetricDefinition]) -> str:
    governed = [r for r in rows if r.role == "governed"]
    base = [r for r in rows if r.role != "governed"]
    lines = [
        "# Metric catalogue",
        "",
        "Generated by `services/metrics_sync/metrics_sync.py` from the dbt semantic manifest.",
        "Do not edit by hand: change `dbt/models/semantic/_metrics.yml` and regenerate.",
        "",
        "Every metric is defined once in dbt (MetricFlow, on `gold.fct_trip`) with the same",
        "computation as an aggregate expression over the published tables of `analytics`",
        "(`sql_expression`), which Superset and the AI assistant copy. Approved metrics use",
        "valid trips only unless stated otherwise.",
        "",
        (
            f"{len(governed)} governed metrics (12 required by the exam, marked *) and "
            f"{len(base)} base metrics used as numerators and denominators."
        ),
        "",
        "## Governed metrics",
        "",
        "| Metric | Definition | Unit | Filters | Grains | Owner |",
        "|---|---|---|---|---|---|",
    ]
    for r in governed:
        star = " *" if r.required_by_exam else ""
        estimate = " **Estimate.**" if r.is_estimate else ""
        lines.append(
            f"| `{r.name}`{star} | {r.label}: {r.description}{estimate} | {r.unit} | "
            f"{r.filters} | {', '.join(r.grains)} | {r.owner} |"
        )
    lines += ["", "## Formulas", ""]
    for r in governed + base:
        lines += [
            f"### `{r.name}` ({r.metric_type}{', base' if r.role != 'governed' else ''})",
            "",
            f"- MetricFlow inputs: {', '.join(r.inputs) or '-'}",
            f"- MetricFlow filter: `{r.metricflow_filter}`"
            if r.metricflow_filter
            else "- MetricFlow filter: none",
            f"- Published expression on `{r.base_table}`:",
            "",
            "```sql",
            r.sql_expression,
            "```",
            "",
        ]
        if r.source:
            lines += [f"- Source: {r.source}", ""]
    lines += [
        "## Dimensions",
        "",
        "Time: `metric_time` (day, week, month; hour for demand metrics) from the pickup time.",
        "Trip: `quality_status`, `is_airport_trip`, `is_tip_recorded`, `pickup_hour`,",
        "`day_of_week`, `service_period`, `source_month`. Joined: pickup and dropoff borough,",
        "zone and market segment; payment type; rate code; vendor; day type and public holiday.",
        "",
    ]
    return "\n".join(lines)


DDL = """
CREATE TABLE IF NOT EXISTS semantic.metric_catalog (
    name text PRIMARY KEY,
    label text NOT NULL,
    description text NOT NULL,
    metric_type text NOT NULL,
    role text NOT NULL,
    required_by_exam boolean NOT NULL,
    owner text NOT NULL,
    unit text,
    grains text[] NOT NULL,
    base_table text NOT NULL,
    sql_expression text NOT NULL,
    filters text,
    is_estimate boolean NOT NULL,
    metricflow_filter text,
    inputs text[],
    source text,
    synced_at timestamptz NOT NULL DEFAULT now()
)
"""


def write_database(rows: list[MetricDefinition]) -> int:
    import psycopg  # only needed for this command

    with psycopg.connect() as conn, conn.cursor() as cur:
        cur.execute(DDL)
        cur.execute(
            "COMMENT ON TABLE semantic.metric_catalog IS 'Governed metric definitions "
            "copied from the dbt semantic layer by metrics-sync.'"
        )
        cur.execute("DELETE FROM semantic.metric_catalog")
        for r in rows:
            d = asdict(r)
            cur.execute(
                """
                INSERT INTO semantic.metric_catalog
                    (name, label, description, metric_type, role, required_by_exam, owner, unit,
                     grains, base_table, sql_expression, filters, is_estimate,
                     metricflow_filter, inputs, source)
                VALUES (%(name)s, %(label)s, %(description)s, %(metric_type)s, %(role)s,
                        %(required_by_exam)s, %(owner)s, %(unit)s, %(grains)s, %(base_table)s,
                        %(sql_expression)s, %(filters)s, %(is_estimate)s,
                        %(metricflow_filter)s, %(inputs)s, %(source)s)
                """,
                d,
            )
    return len(rows)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=["markdown", "database"])
    parser.add_argument("--manifest", type=Path, default=Path("dbt/target/semantic_manifest.json"))
    parser.add_argument("--out", type=Path, default=Path("docs/metric_catalog.md"))
    args = parser.parse_args(argv)

    rows = load_catalog(args.manifest)
    if args.command == "markdown":
        args.out.write_text(to_markdown(rows), encoding="utf-8")
        print(f"wrote {args.out} ({len(rows)} metrics)")
    else:
        print(f"semantic.metric_catalog: {write_database(rows)} metrics")
    return 0


if __name__ == "__main__":
    sys.exit(main())
